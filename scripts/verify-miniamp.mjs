import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const results = []
await fs.mkdir('output/miniamp', { recursive: true })
try {
  for (const phone of [false, true]) {
    const page = await browser.newPage({ viewport: phone ? { width: 390, height: 800 } : { width: 1280, height: 760 }, isMobile: phone, hasTouch: phone, deviceScaleFactor: phone ? 3 : 1 })
    const errors = []
    page.on('pageerror', (e) => errors.push(e.message))
    await page.addInitScript(() => localStorage.setItem('playback.theme', 'paper'))
    await page.goto(`${process.env.TOKYO_URL || 'http://127.0.0.1:4173'}/?sky=night&verifyTokyo=1&animateTrain=1`, { waitUntil: 'domcontentloaded' })
    await page.getByText('Try it with sample CDs').click()
    await page.waitForFunction(() => window.__tokyo?.backdropCalls > 0, undefined, { timeout: 60000 })
    const streetPixelRatio = await page.evaluate(() => window.__tokyo.pixelRatio)
    assert.equal(streetPixelRatio, phone ? 1.5 : 2, 'Street keeps its quality render scale after Canvas updates')
    assert.equal(await page.evaluate(() => window.__tokyo.shadowSize), phone ? 2048 : 8192)
    const train = await page.evaluate(() => window.__tokyo.trainX)
    await page.waitForFunction((x) => window.__tokyo.trainX !== x, train, { timeout: 30000 })
    if (phone) {
      const cdp = await page.context().newCDPSession(page)
      await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: 280, y: 440 }] })
      for (let i = 1; i <= 8; i++) {
        await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: 280, y: 440 - i * 24 }] })
      }
      await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    } else await page.getByRole('button', { name: 'Row below' }).click()
    await page.waitForFunction(() => document.querySelector('.row-header')?.textContent.includes('Row 2'))
    await page.waitForTimeout(2200)
    if (phone) await page.touchscreen.tap(170, 355)
    else await page.mouse.click(600, 370)
    await page.getByText('Tap the case to open it', { exact: true }).waitFor({ timeout: 15000 })
    await page.waitForTimeout(1800)
    if (phone) await page.touchscreen.tap(195, 370)
    else await page.mouse.click(640, 360)
    await page.getByRole('button', { name: 'Tracks', exact: true }).waitFor({ timeout: 15000 })
    assert.equal(await page.locator('.panel').count(), 0)
    await page.getByRole('button', { name: 'Play CD', exact: false }).click()
    await page.locator('.nowbar').waitFor()
    assert.match(await page.locator('.nowbar').textContent(), /Liked|Paper|Intro/)
    const deck = page.locator('.miniamp')
    if (phone) {
      assert.equal(await deck.locator('canvas').count(), 0)
      await deck.getByRole('button', {name: 'Expand player'}).click()
    }
    assert.equal(await page.getByRole('button', {name: 'Play CD', exact: false}).count(), 0)
    assert.equal(await page.locator('.rhythm, .mood').count(), 0)
    await deck.getByText('Animation · not audio analysis').waitFor()
    const wave = () => deck.locator('canvas').evaluate(c => c.toDataURL())
    const moving = await wave()
    await page.waitForTimeout(900)
    assert.notEqual(await wave(), moving)
    await deck.getByRole('button', {name:'Pause',exact:true}).click()
    await page.waitForTimeout(200)
    const frozen = await wave()
    await page.waitForTimeout(700)
    assert.equal(await wave(), frozen)
    const slider = deck.getByRole('slider', {name:'Playback position'})
    await slider.focus()
    await page.keyboard.press('ArrowRight')
    assert(Number(await slider.inputValue()) >= 1000)
    await deck.getByRole('button',{name:'Play',exact:true}).click()
    await page.emulateMedia({reducedMotion:'reduce'})
    await page.waitForTimeout(200)
    const reduced = await wave()
    await page.waitForTimeout(600)
    assert.equal(await wave(), reduced)
    await page.emulateMedia({reducedMotion:'no-preference'})
    await deck.getByRole('button',{name:'Collapse player'}).click()
    assert.equal(await deck.locator('canvas').count(),0)
    await deck.getByRole('button',{name:'Expand player'}).click()
    await page.waitForTimeout(600)
    await page.screenshot({path:`output/miniamp/${phone?'phone':'desktop'}-street.png`})
    const bounds = await deck.boundingBox()
    await page.getByRole('button', {name: 'Tracks', exact: true}).click()
    await page.waitForTimeout(600)
    const panelBounds = await page.locator('.panel').boundingBox()
    assert(panelBounds.y + panelBounds.height <= bounds.y, 'Player must not overlap track panel')

    await page.getByRole('button', {name: 'Close tracks'}).click()
    assert.equal(await page.locator('.panel').count(), 0)
    await page.getByRole('button', { name: 'Back to collection', exact: false }).click()
    await page.waitForTimeout(1500)
    assert.equal(await page.locator('.theme-toggle, main.paper').count(), 0)
    await page.locator('main.street').waitFor()
    assert.deepEqual(errors, [])
    results.push({ device: phone ? 'phone' : 'desktop', train: 'moves', navigation: phone ? 'touch swipe' : 'row button', pickOpenPlayReturn: 'pass', streetOnly: 'pass', streetPixelRatio, errors })
    console.log(results.at(-1))
    await page.close()
  }
} finally {
  await browser.close()
  await fs.writeFile('output/miniamp/checks.json', JSON.stringify(results, null, 2))
}
